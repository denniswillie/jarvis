"""Standalone sandbox helper. Uses only Python's standard library.

Usage: python .jarvis/wake_agent.py --event-id result-123 --message-file result.txt
Scripts may import notify() instead. Keep the same event ID AND message when
retrying an uncertain delivery. A successful return means admitted, not answered.
The adjacent wake.json is provisioned by Jarvis, not generated by the model.
"""
import argparse
import json
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener


class WakeDeliveryError(RuntimeError):
    pass


class _NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, request, fp, code, message, headers, new_url):
        raise HTTPError(request.full_url, code, "Callback redirect refused", headers, fp)


def _open(request, *, timeout):
    return build_opener(_NoRedirect()).open(request, timeout=timeout)


def notify(event_id: str, message: str, *, config_path=None):
    if (not isinstance(event_id, str) or not event_id.strip() or len(event_id) > 256
            or "\0" in event_id):
        raise ValueError("A stable event ID of at most 256 characters is required")
    if not isinstance(message, str) or not message.strip() or len(message.encode()) > 4096:
        raise ValueError("Send at most 4096 bytes; leave large results in a file")
    path = Path(config_path) if config_path is not None else Path(__file__).with_name("wake.json")
    config = json.loads(path.read_text())
    endpoint = config["endpoint"]
    url = urlsplit(endpoint)
    if url.scheme != "https" or not url.hostname or url.username or url.password or url.fragment or url.query:
        raise ValueError("The configured wake endpoint must be a plain HTTPS URL")
    body = json.dumps({"session_id": config["session_id"], "event_id": event_id,
                       "message": message}, ensure_ascii=False).encode()
    request = Request(endpoint, data=body, method="POST", headers={
        "Authorization": "Bearer " + config["token"], "Content-Type": "application/json"})
    try:
        with _open(request, timeout=20) as response:
            raw = response.read(32769)
            if response.status != 202 or len(raw) > 32768:
                raise WakeDeliveryError("Admission unconfirmed; retry the same event ID and message")
            try:
                receipt = json.loads(raw)
            except (ValueError, UnicodeError):
                raise WakeDeliveryError("Admission unconfirmed; retry the same event ID and message") from None
            if (not isinstance(receipt, dict) or receipt.get("delivery") != "admitted"
                    or receipt.get("session_id") != config["session_id"]
                    or not isinstance(receipt.get("admission_id"), str) or not receipt["admission_id"]):
                raise WakeDeliveryError("Admission unconfirmed; retry the same event ID and message")
            return receipt
    except HTTPError as error:
        if 300 <= error.code < 400:
            raise WakeDeliveryError("Callback redirect refused; check the configured endpoint") from None
        if error.code == 409:
            raise WakeDeliveryError("This event ID already has different content; do not silently replace it") from None
        if error.code in (400, 401, 403, 413):
            raise WakeDeliveryError("Callback refused (HTTP %s); check configuration and message" % error.code) from None
        raise WakeDeliveryError("Admission unconfirmed; retry the same event ID and message") from None
    except (URLError, TimeoutError, OSError):
        raise WakeDeliveryError("Network unavailable; admission unknown. Retry the same event ID and message") from None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--event-id", required=True)
    content = parser.add_mutually_exclusive_group(required=True)
    content.add_argument("--message")
    content.add_argument("--message-file", type=Path)
    args = parser.parse_args()
    try:
        message = args.message if args.message_file is None else args.message_file.read_text()
        receipt = notify(args.event_id, message)
    except WakeDeliveryError as error:
        print(json.dumps({"delivery": "unconfirmed", "message": str(error)}))
        return 1
    except (KeyError, ValueError, OSError):
        print(json.dumps({"delivery": "not_sent", "message": "Invalid wake configuration or message"}))
        return 2
    print(json.dumps({"delivery": "admitted", "admission_id": receipt["admission_id"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
